import type { Swap, SwapPart, Unit } from '../types';

// What to use when you don't have an ingredient. Each part's amount = the recipe's amount (converted to `u` when given)
// × f. A count line (e.g. "3 cloves garlic") swapped to a spoon unit uses f per piece.
// A part is [ingredient, f, unit?, fc?]: fc = amount per piece when the recipe line is a count (3 cloves, 1 bunch).
const s = (note: string, ...parts: [string, number, string?, number?][]): Swap => ({
  note,
  parts: parts.map(([ing, f, u, fc]) => {
    const p: SwapPart = { ing, f };
    if (u) p.u = u as Unit;
    if (fc !== undefined) p.fc = fc;
    return p;
  }),
});

